import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const proSwingsDir = path.join(root, "public", "pro-swings");
const outputFile = path.join(root, "lib", "data", "pro-swings.generated.ts");
const thumbnailExtensions = [".jpg", ".jpeg", ".png", ".webp"];

function toWords(value) {
  return value
    .replace(/\.[^.]+$/, "")
    .replace(/[_-]+/g, " ")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/\s+/g, " ")
    .trim();
}

function toSlug(value) {
  return toWords(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function findThumbnail(baseName, files) {
  const lowerBaseName = baseName.toLowerCase();
  const thumbnail = files.find((file) => {
    const parsed = path.parse(file);
    return (
      parsed.name.toLowerCase() === lowerBaseName &&
      thumbnailExtensions.includes(parsed.ext.toLowerCase())
    );
  });

  return thumbnail ? `/pro-swings/${thumbnail}` : "/file.svg";
}

const files = await readdir(proSwingsDir);
const videos = files
  .filter((file) => path.extname(file).toLowerCase() === ".mp4")
  .sort((a, b) => a.localeCompare(b));

const references = videos.map((file) => {
  const baseName = path.basename(file, path.extname(file));
  const label = toWords(baseName);

  return {
    id: `pro-${toSlug(baseName)}`,
    player: label,
    title: label,
    club: "Unknown",
    viewAngle: "face-on",
    handedness: "right",
    fps: 30,
    duration: 0,
    tags: [],
    videoUrl: `/pro-swings/${file}`,
    thumbnailUrl: findThumbnail(baseName, files),
  };
});

const source = `import type { ProSwingReference } from "@/lib/types";

// Generated by scripts/generate-pro-swings-manifest.mjs.
// Do not edit by hand. Add .mp4 files to public/pro-swings and run npm run pro-swings:generate.
export const generatedProSwingReferences: ProSwingReference[] = ${JSON.stringify(
  references,
  null,
  2,
)};
`;

await writeFile(outputFile, source);

console.log(`Generated ${references.length} pro swing reference${references.length === 1 ? "" : "s"}.`);
